const {test}=require('node:test'),assert=require('node:assert/strict')
require('./setup.cjs')
const {buildContext}=require('../electron/social-brain/context-builder.cjs')
const {parsePlan}=require('../electron/social-brain/conversation-planner.cjs')
const {writeReply}=require('../electron/social-brain/reply-writer.cjs')
const now=new Date(),row=(id,role,text)=>({id,role,text,at:now.toISOString()})
const contact=messages=>({id:'momentum-test',profile:{chatMode:'friendship'},learning:{messages}})
const json=patch=>JSON.stringify({plan:{shouldReply:true,action:'ACK',goal:'回应当前焦点',...patch},learning:{enabled:false}})
test('ongoing new thread keeps focus aligned after a continuation beyond the initial shift',()=>{
  const c=contact([row('old','contact','考研学校还没定，挺纠结'),row('shift','contact','对了最近准备养小猫'),row('new','contact','小猫的名字还没想好')])
  const ctx=buildContext({contact:c,incoming:'小猫的名字还没想好',now})
  assert.match(ctx.payload.attentionContext.activeTopic.summary,/小猫/)
  assert.ok(ctx.conversationState.activeTopic.sourceMessageIds.includes(ctx.attention.selectedFocus.messageId))
  assert.notEqual(ctx.attention.selectedFocus.messageId,'old')
})
test('an actual earlier response does not permanently resolve a still undecided paused choice',()=>{
  const c=contact([row('old','contact','考研还没决定学校'),row('reply','me','慢慢选'),row('cat','contact','对了我养了小猫'),row('owner','me','猫咪挺可爱的'),row('done','contact','这个搞定了')])
  c.learning.relationshipPlan={focusMessageId:'old',generatedReply:'慢慢选',at:now.toISOString()}
  const ctx=buildContext({contact:c,incoming:'这个搞定了',now})
  assert.equal(ctx.attention.recommendedMode,'START_NEW_TOPIC');assert.equal(ctx.momentum.continuation.strategy,'RETURN_TOPIC')
})
test('returning to an undecided target university permits a grounded question without learning current school',async()=>{
  const c=contact([row('old','contact','考研还没决定学校'),row('reply','me','慢慢选'),row('cat','contact','对了我养了小猫'),row('owner','me','猫咪挺可爱的'),row('done','contact','这个搞定了')])
  const ctx=buildContext({contact:c,incoming:'这个搞定了',now}),plan=parsePlan(json({action:'FOLLOW_UP',allowQuestion:true}),ctx)
  assert.equal(plan.topicSourceId,ctx.attention.topicSource.evidenceId)
  const reply=await writeReply(async()=>({text:'你考研学校后来定了吗？'}),ctx,plan)
  assert.match(reply.text,/考研/);assert.equal(ctx.memory.profile.identity.school.status,'unknown')
  assert.throws(()=>parsePlan(json({topicSourceId:'other-contact-secret'}),ctx),/未知的回题来源/)
})
test('small prompt budget preserves last input and focus while keeping full state locally',()=>{
  const c=contact(Array.from({length:30},(_,i)=>row('m'+i,i%2?'me':'contact','最近准备考研，目标学校还没决定。'.repeat(15))))
  c.learning.messages.push(row('last','contact','北航吧，不过感觉很难'))
  const ctx=buildContext({contact:c,incoming:'北航吧，不过感觉很难',now,tokenBudget:1800})
  assert.ok(ctx.estimatedTokens<=1800);assert.match(ctx.payload.incoming,/北航/)
  assert.ok(ctx.conversationState.topicTree.length);assert.equal(ctx.payload.conversationState.topicTree,undefined)
})
test('a first-person how-to learning statement is disclosure rather than a direct question',()=>{
  const c=contact([row('a','contact','我最近准备养小猫'),row('q1','me','你喜欢什么猫？'),row('b','contact','我喜欢安静的'),row('q2','me','你怎么照顾呀？'),row('new','contact','我已经准备好了猫砂盆，最近一直在了解怎么照顾')])
  const ctx=buildContext({contact:c,incoming:c.learning.messages.at(-1).text,now,persona:{identity:'虚拟机械专业大学生',interests:'宠物'}})
  assert.equal(ctx.attention.selectedFocus.directQuestion,0);assert.equal(ctx.momentum.continuation.strategy,'SHARE')
  const plan=parsePlan(json({action:'ANSWER'}),ctx);assert.equal(plan.action,'SHARE');assert.equal(plan.allowQuestion,false)
})
test('an explicit request for how-to help retains direct-question priority',()=>{
  const c=contact([row('ask','contact','我想请教你，怎么照顾小猫？')])
  const ctx=buildContext({contact:c,incoming:c.learning.messages[0].text,now})
  assert.equal(ctx.attention.selectedFocus.directQuestion,1);assert.equal(ctx.momentum.continuation.strategy,'ANSWER')
})
