test('known major prevents asking it again, while explicit new city corrects an old fact', () => {
  let c = contact([msg('我专业是机械工程', 'contact', 'a'), msg('我在杭州上班', 'contact', 'b')])
  const old = syncMemory(c, { now })
  c = { ...c, socialBrain: old, learning: { messages: [...c.learning.messages, msg('我现在搬到广州上班了', 'contact', 'c', '2026-10-11T04:00:00Z')] } }
  const memory = syncMemory(c, { now: new Date('2026-10-11T04:00:00Z') })
  assert.equal(memory.profile.identity.city.value, '广州')
  assert.equal(detectLearningOpportunity({ memory, incoming: '今天老师让画图', now }).enabled, false)
})
