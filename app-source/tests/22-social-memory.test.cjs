test('future date resolution uses Shanghai calendar at the UTC day boundary', () => {
  const at = '2026-10-09T17:00:00Z'
  assert.equal(localDay(at), '2026-10-10')
  assert.equal(eventFromMessage(msg('我明天面试', 'contact', 'x', at)).dueDate, '2026-10-11')
  const historical = contact([msg('我下周一面试', 'contact', 'old', '')])
  const context = buildContext({ contact: historical, incoming: '我下周一面试', now })
  assert.equal(context.messages[0].at, '')
  assert.equal(context.memory.events[0].dueDate, null)
  assert.equal(context.memory.events[0].followUp.status, 'needs_date')
})
test('repeated scans are idempotent and keep archived legacy notes unverified', () => {
  const c = { ...contact([msg('我下周一面试')]), learning: { messages: [msg('我下周一面试')], facts: ['在北京上班'] } }
  const first = syncMemory(c, { now })
  const second = syncMemory({ ...c, socialBrain: first }, { now })
  assert.equal(second.events.length, 1)
  assert.equal(second.facts.length, first.facts.length)
  assert.equal(second.legacyMemories[0].status, 'unverified_legacy')
  assert.equal(second.profile.identity.city.status, 'unknown')
})
test('context is bounded, keeps the latest message, and excludes explicit style samples in friendship', () => {
  const c = contact(Array.from({ length: 60 }, (_, i) => msg(`第${i}条聊天记录${'普通内容'.repeat(30)}`, i % 2 ? 'contact' : 'me', String(i))))
  c.profile.examples = ['STYLE_SECRET']; c.profile.tone = 'TONE_SECRET'
  const context = buildContext({ contact: c, incoming: c.learning.messages.at(-1).text, persona: { tone: 'PERSONA_TONE_SECRET', examples: 'PERSONA_STYLE_SECRET', identity: '大学生' }, now, tokenBudget: 2500 })
  const serialized = JSON.stringify(context.payload)
  assert.ok(estimateTokens(context.payload) <= 2500)
  assert.match(serialized, /第59条/)
  assert.doesNotMatch(serialized, /STYLE_SECRET|TONE_SECRET/)
})
