test('JSON persistence, restart and derived Markdown retain evidence and user settings', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'douyin-social-memory-'))
  try {
    const c = contact([msg('我是湖南人'), msg('我下周一面试', 'contact', 'e')])
    c.socialBrain = syncMemory(c, { now })
    const storage = new JsonStorage(dir)
    storage.update({ contacts: [c], automation: { autoReply: true, maxPerContactDailyEnabled: false } })
    const restored = new JsonStorage(dir).get()
    assert.equal(restored.contacts[0].socialBrain.profile.identity.province.value, '湖南')
    assert.equal(restored.contacts[0].socialBrain.events[0].dueDate, '2026-10-12')
    assert.equal(restored.automation.autoReply, true)
    const folder = path.join(dir, 'social-brain', fs.readdirSync(path.join(dir, 'social-brain'))[0])
    for (const name of ['profile.json', 'events.json', 'memories.json', 'style.json', 'relationship.json', 'learning-history.json', 'summary.md']) assert.ok(fs.existsSync(path.join(folder, name)))
    assert.match(fs.readFileSync(path.join(folder, 'summary.md'), 'utf8'), /待跟进|湖南/)
    assert.equal(JSON.parse(fs.readFileSync(path.join(folder, 'profile.json'), 'utf8')).identity.province.status, 'fact')
  } finally { assert.equal(path.dirname(path.resolve(dir)), path.resolve(os.tmpdir())); assert.ok(path.basename(dir).startsWith('douyin-social-memory-')); fs.rmSync(dir, { recursive: true, force: true }) }
})
test('migration preserves old friend profiles, examples and legacy learning without promoting old notes', () => {
  const input = { contacts: [{ name: '旧友', profile: { chatMode: 'oldfriend', examples: ['好嘞'], relationship: '室友' }, learning: { facts: ['在北京上班'], messages: [] } }] }
  const restored = migrateLegacy(input)
  assert.deepEqual(restored.contacts[0].profile, input.contacts[0].profile)
  assert.deepEqual(restored.contacts[0].learning.facts, input.contacts[0].learning.facts)
  assert.equal(restored.contacts[0].socialBrain.profile.identity.city.status, 'unknown')
  assert.equal(normalizeMemory({ inferences: [null], legacyMemories: 'bad' }).inferences.length, 0)
})
