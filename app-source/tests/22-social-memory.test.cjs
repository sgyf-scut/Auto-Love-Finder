const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
require('./setup.cjs')
const { syncMemory, applyObservations, messageList, eventFromMessage, localDay, normalizeMemory } = require('../electron/social-brain/memory-manager.cjs')
const { buildContext, detectLearningOpportunity, estimateTokens } = require('../electron/social-brain/context-builder.cjs')
const { parsePlan, ACTIONS } = require('../electron/social-brain/conversation-planner.cjs')
const { JsonStorage, migrateLegacy } = require('../electron/storage.cjs')
const now = new Date('2026-10-10T12:00:00+08:00')
const msg = (text, role = 'contact', id = 'm1', at = now.toISOString()) => ({ role, text, id, at })
const contact = messages => ({ id: 'target', name: '验收对象', profile: { chatMode: 'friendship' }, learning: { messages } })
const rawPlan = (action = 'FOLLOW_UP', topic = 'major') => JSON.stringify({ plan: { shouldReply: true, action, goal: '顺着当前话题接话' }, learning: { enabled: true, topic, shouldAsk: true, naturalness: 0.96 }, observations: {}, advisor: { needed: false } })

test('acceptance 1: explicit Hunan origin becomes an evidenced province fact', () => {
  const memory = syncMemory(contact([msg('我是湖南人。')]), { now })
  assert.equal(memory.profile.identity.province.value, '湖南')
  assert.equal(memory.profile.identity.province.status, 'fact')
  assert.deepEqual(memory.profile.identity.province.sourceMessageIds, ['m1'])
  assert.equal(memory.profile.identity.city.status, 'unknown')
})
test('acceptance 2: a boss asking overtime proves circumstances, never programmer', () => {
  const c = contact([msg('老板让我加班。')])
  const memory = syncMemory(c, { now })
  assert.ok(memory.facts.some(f => f.field === 'current_life'))
  const updated = applyObservations(memory, { facts: [{ field: 'occupation', value: '程序员', evidence: '老板让我加班', evidenceMessageId: 'm1' }] }, messageList(c), now)
  assert.equal(updated.profile.identity.occupation.status, 'unknown')
  assert.equal(updated.profile.identity.occupation.value, null)
})
test('acceptance 3: a naturally occurring school topic permits learning about major', () => {
  const context = buildContext({ contact: contact([msg('刚下课，今天老师又让我们画结构图')]), incoming: '刚下课，今天老师又让我们画结构图', now })
  assert.equal(context.opportunity.enabled, true)
  assert.equal(context.opportunity.topic, 'major')
  assert.equal(context.opportunity.shouldAsk, true)
  assert.equal(parsePlan(rawPlan(), context).learningOpportunity.shouldAsk, true)
})
test('acceptance 4: two question turns block exploration even below aggregate pressure threshold', () => {
  const messages = [msg('好呀', 'me', 'o1'), msg('明白', 'me', 'o2'), msg('不错', 'me', 'o3'), msg('哈哈', 'me', 'o4'), msg('你在哪个城市？', 'me', 'o5'), msg('广州', 'contact', 'c5'), msg('你喜欢什么？', 'me', 'o6'), msg('今天老师让我们画结构图', 'contact', 'c6')]
  const context = buildContext({ contact: contact(messages), incoming: messages.at(-1).text, now })
  assert.ok(context.memory.relationshipMetrics.questionPressure <= 0.55)
  assert.equal(context.memory.relationshipMetrics.consecutiveQuestions, 2)
  const plan = parsePlan(rawPlan('SHARE_AND_ASK'), context)
  assert.equal(plan.learningOpportunity.shouldAsk, false)
  assert.equal(plan.action, 'EMPATHY')
})
test('acceptance 5: next Monday interview records an event and a future follow-up', () => {
  const memory = syncMemory(contact([msg('我下周一面试。')]), { now })
  assert.equal(memory.events.length, 1)
  assert.equal(memory.events[0].type, 'interview')
  assert.equal(memory.events[0].dueDate, '2026-10-12')
  assert.equal(memory.events[0].followUp.notBefore, '2026-10-13')
  assert.equal(memory.events[0].followUp.status, 'pending')
})
test('owner statements, unknown senders, third-party quotes, questions and hypotheses cannot form identity facts', () => {
  for (const m of [msg('我是程序员', 'me'), msg('我是程序员', 'unknown'), msg('我朋友说我是程序员'), msg('我是不是程序员？'), msg('如果我是程序员'), msg('我不是程序员')]) {
    assert.equal(syncMemory(contact([m]), { now }).profile.identity.occupation.status, 'unknown')
  }
})
test('source ID and quote are checked against the current contact, not the owner', () => {
  const c = contact([msg('我是程序员', 'me', 'owner'), msg('我是湖南人', 'contact', 'friend')])
  const memory = applyObservations(syncMemory(c, { now }), { facts: [{ field: 'occupation', value: '程序员', evidence: '我是程序员', evidenceMessageId: 'owner' }, { field: 'city', value: '广州', evidence: '我在广州上班', evidenceMessageId: 'another_contact' }] }, messageList(c), now)
  assert.equal(memory.profile.identity.occupation.status, 'unknown')
  assert.equal(memory.profile.identity.city.status, 'unknown')
})
test('inferences remain labelled guesses and never populate identity', () => {
  const c = contact([msg('老板让我加班')])
  const memory = applyObservations(syncMemory(c, { now }), { inferences: [{ content: '可能工作压力大', confidence: 0.99, evidence: '老板让我加班', evidenceMessageId: 'm1' }] }, messageList(c), now)
  assert.equal(memory.inferences[0].status, 'inference')
  assert.equal(memory.inferences[0].confidence, 0.8)
  assert.equal(memory.profile.identity.occupation.status, 'unknown')
})
test('actual major question and short answer produce an answered learning attempt', () => {
  const memory = syncMemory(contact([msg('你学什么专业？', 'me', 'q'), msg('机械啊', 'contact', 'a')]), { now })
  assert.equal(memory.profile.identity.major.value, '机械')
  assert.equal(memory.learningHistory.length, 1)
  assert.equal(memory.learningHistory[0].result, 'answered')
})
test('avoided questions enter a cooldown and are not asked again on a new topic cue', () => {
  const memory = syncMemory(contact([msg('你做什么工作？', 'me', 'q'), msg('不方便说', 'contact', 'a')]), { now })
  assert.equal(memory.learningHistory[0].result, 'avoided')
  assert.equal(memory.learningHistory[0].cooldownUntil, '2026-10-20')
  const context = buildContext({ contact: { ...contact([msg('你做什么工作呢？', 'contact', 'b')]), socialBrain: memory }, incoming: '你做什么工作呢？', now })
  assert.equal(context.opportunity.shouldAsk, false)
})
